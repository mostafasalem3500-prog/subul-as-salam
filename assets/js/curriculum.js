// عناصر المحطة لِلُغة معيّنة → قائمة مهام موحّدة
export function stageTasks(stage, lang) {
  const tasks = [];
  (stage.ih[lang] || []).forEach((id) => tasks.push({ key: `ih:${id}`, kind: 'read', id }));
  stage.quran.forEach((n) => tasks.push({ key: `quran:${n}`, kind: 'memorize', id: n }));
  return tasks;
}

